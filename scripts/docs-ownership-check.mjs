#!/usr/bin/env node
/**
 * docs-ownership-check.mjs — single-source facts stay single-source.
 *
 * Some facts in this repo have exactly one home (the ownership table in the
 * docs overhaul: verify-pipeline step list -> AGENTS.md, contract versions ->
 * docs/architecture/CONTRACTS.md, changeset exemptions -> AGENTS.md, ...).
 * Every other page links to the home instead of restating the fact, so the
 * copies can't drift. This check greps the tracked tree for restatements and
 * fails when one appears outside its home.
 *
 * Run locally:   pnpm docs:ownership          (or: node scripts/docs-ownership-check.mjs)
 * List rules:    node scripts/docs-ownership-check.mjs --list-rules
 * CI:            .github/workflows/docs.yml (markdownlint job)
 *
 * How to extend
 * -------------
 * Add an entry to RULES below. Each rule is:
 *   id      — short stable identifier, shown in the output
 *   pattern — RegExp run against whole-file content (use [^\n] to keep a
 *             match on one line; plain \s* tolerates wrapped lines)
 *   include — glob(s) selecting which tracked files the rule scans
 *   allow   — glob(s) for the fact's home(s); matches there are fine
 *   message — one line telling the author where the fact lives
 *
 * Allowlist philosophy: when the check flags something legitimate, prefer
 * TIGHTENING THE PATTERN over widening the allowlist. A wider allowlist
 * silently exempts future drift in that file; a tighter pattern keeps the
 * rule honest everywhere. Only allowlist a file when it genuinely is (part
 * of) the fact's home, and leave a dated comment saying why.
 *
 * Zero dependencies; file list comes from `git ls-files`, so gitignored
 * trees (.local-plugins/, dist/, node_modules/) are never scanned.
 */

import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { dirname, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Globs skipped for every rule: generated files and this script itself. */
const GLOBAL_EXCLUDES = [
  "scripts/docs-ownership-check.mjs", // contains the patterns it hunts for
  "**/etc/*.api.md", // API Extractor output — regenerated by `pnpm api-check`
  "pnpm-lock.yaml",
];

const RULES = [
  {
    id: "verify-pipeline",
    // The enumerated `pnpm verify` step list ("lint → check-types → build →
    // ..." / "lint + check-types + build + ..."), including its tail
    // ("contract → api-check"). Two patterns so a partial restatement of
    // either end of the pipeline is still caught.
    patterns: [
      /lint\s*(?:→|\+|,)\s*(?:check-types|type-?check)\s*(?:→|\+|,)\s*build/g,
      // Arrow/plus separators only: a comma list like "lint-types, unit,
      // contract, api-check" is the CI *job-id* list (homed in the
      // workflows), not the verify step list.
      /(?:test:contract|contract(?:\s+tests?)?)\s*(?:→|\+)\s*api-check/g,
    ],
    include: ["**"],
    allow: [
      "AGENTS.md", // the home: AGENTS.md § Pre-push gate — `pnpm verify`
      "package.json", // the scripts themselves
      "turbo.json", // the task graph itself
      ".github/workflows/**", // the CI jobs themselves
    ],
    message:
      "the `pnpm verify` step list lives once in AGENTS.md § Pre-push gate — link there instead of enumerating the steps",
  },
  {
    id: "contract-version-pair",
    // A contract name paired with a version number ("Manifest 1.1",
    // "Runtime API 1.0", "Theme Contract 2.0", ...). Versions live in code
    // (apiVersion.ts) and are documented once in CONTRACTS.md; everywhere
    // else says "the ... contract" and links, so a bump can't strand stale
    // numbers. Only markdown is scanned — code is a legitimate holder.
    patterns: [
      /\b(?:Manifest|Runtime API|Theme|Config(?:uration)?)(?:\s+Contract)?\s+v?\d+\.\d/g,
    ],
    include: ["**/*.md", "llms.txt"],
    allow: [
      "docs/architecture/CONTRACTS.md", // the home
      "docs/architecture/decisions/**", // ADRs are historical records
      "**/CHANGELOG.md", // generated release history
      ".changeset/**", // pending release history
      // TEMPORARY (2026-08-12): line 26 says "Manifest 1.1"; the file is
      // owned by the parallel PR #330 right now. Remove this entry once
      // #330 lands and drop the version pair there.
      "docs/plugins/creating-a-plugin.md",
    ],
    message:
      "contract versions live in code and docs/architecture/CONTRACTS.md — name the contract without a number and link there",
  },
  {
    id: "changeset-exemption",
    // Restatements of WHICH packages are changeset-exempt. The authoritative
    // wording (only `.changeset/config.json`'s `ignore` list is exempt) is
    // AGENTS.md § Versioning; everyone else links to it.
    patterns: [
      /\.changeset\/config\.json[^\n]{0,80}`?ignore`?|`?\bignore\b`?[^\n]{0,80}\.changeset\/config\.json/g,
      /`shell`[^\n]{0,30}`playground`[^\n]{0,80}(?:exempt|need none)|(?:exempt|only)[^\n]{0,80}`shell`[^\n]{0,30}`playground`/gi,
    ],
    include: ["**/*.md"],
    allow: [
      "AGENTS.md", // the home: AGENTS.md § Versioning
      "**/CHANGELOG.md",
      ".changeset/**",
    ],
    message:
      "the changeset rule and its exemptions live once in AGENTS.md § Versioning — link there instead of restating the ignore list",
  },
  {
    id: "legacy-plugin-namespace-key",
    // The pre-1.0 config key `app.pluginNamespace` was replaced by
    // `app.enabledPlugins` (Phase 2b). Docs may only name it in the
    // migration/history notes below; anywhere else implies it still works.
    // Code identifiers that merely contain the words (local variables in
    // the shell/i18n packages) are out of scope: only markdown is scanned.
    patterns: [/\bpluginNamespace\b/g],
    include: ["**/*.md", "llms.txt"],
    allow: [
      "docs/architecture/CONFIGURATION.md", // records the rename
      "docs/getting-started/upgrading.md", // pre-1.0 migration step
      "docs/operations/open-followups.md", // historical follow-up log
      "**/CHANGELOG.md",
      ".changeset/**",
    ],
    message:
      "`pluginNamespace` is a removed pre-1.0 config key — only the migration notes (CONFIGURATION.md, upgrading.md, open-followups.md) may name it",
  },
  {
    id: "org-name-leak",
    // Generic-content rule for the public repo: no organization, customer,
    // or internal host names anywhere in the tree. `.changeset/` and the
    // generated CHANGELOGs keep the historical mentions (decision D6,
    // 2026-08-12); everything else must stay generic.
    //
    // The deny-list itself is base64-encoded so this tracked file does not
    // ship the very strings it polices — decoded only at runtime.
    patterns: [
      new RegExp(
        ["dW5pdmll", "dHV3aWVu", "aGlua2Vsc3RlaW4=", "a2xpbmdlZQ=="]
          .map((s) => Buffer.from(s, "base64").toString("utf8"))
          .join("|"),
        "gi",
      ),
    ],
    include: ["**"],
    allow: [".changeset/**", "**/CHANGELOG.md"],
    message:
      "org/customer/host names must not appear in the public tree (generic-content rule) — reword generically",
  },
];

// --- tiny glob matcher (supports **, *, and literal paths) -----------------

function globToRegExp(glob) {
  let re = "";
  let i = 0;
  while (i < glob.length) {
    const ch = glob[i];
    if (ch === "*") {
      if (glob[i + 1] === "*") {
        // `**/` matches zero or more path segments; bare `**` matches rest.
        if (glob[i + 2] === "/") {
          re += "(?:.*/)?";
          i += 3;
        } else {
          re += ".*";
          i += 2;
        }
      } else {
        re += "[^/]*";
        i += 1;
      }
    } else {
      re += ch.replace(/[.+^${}()|[\]\\?]/g, "\\$&");
      i += 1;
    }
  }
  return new RegExp(`^${re}$`);
}

const matchesAny = (path, globs) => globs.some((g) => globToRegExp(g).test(path));

// --- run --------------------------------------------------------------------

if (process.argv.includes("--list-rules")) {
  for (const rule of RULES) {
    console.log(`${rule.id}`);
    console.log(`  scans:   ${rule.include.join(", ")}`);
    console.log(`  allowed: ${rule.allow.join(", ")}`);
    console.log(`  ${rule.message}`);
    console.log("");
  }
  process.exit(0);
}

const trackedFiles = execFileSync("git", ["ls-files", "-z"], {
  cwd: repoRoot,
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
})
  .split("\0")
  .filter(Boolean)
  .map((p) => p.split(sep).join("/"))
  .filter((p) => !matchesAny(p, GLOBAL_EXCLUDES));

const lineOfIndex = (content, index) =>
  content.slice(0, index).split("\n").length;

let violations = 0;

for (const file of trackedFiles) {
  const relevantRules = RULES.filter(
    (rule) => matchesAny(file, rule.include) && !matchesAny(file, rule.allow),
  );
  if (relevantRules.length === 0) continue;

  let content;
  try {
    content = readFileSync(resolve(repoRoot, file), "utf8");
  } catch {
    continue; // unreadable (e.g. deleted locally) — nothing to scan
  }
  if (content.includes("\0")) continue; // binary

  for (const rule of relevantRules) {
    for (const pattern of rule.patterns) {
      pattern.lastIndex = 0;
      for (const match of content.matchAll(pattern)) {
        violations += 1;
        const line = lineOfIndex(content, match.index);
        const snippet = match[0].replace(/\s+/g, " ").slice(0, 80);
        console.error(`${file}:${line}: [${rule.id}] "${snippet}"`);
        console.error(`  -> ${rule.message}`);
      }
    }
  }
}

if (violations > 0) {
  console.error(
    `\ndocs-ownership-check: ${violations} violation(s). A single-source fact is restated outside its home — link to the home instead (see the header of scripts/docs-ownership-check.mjs).`,
  );
  process.exit(1);
}

console.log(
  `docs-ownership-check: OK — ${trackedFiles.length} tracked files scanned, ${RULES.length} rules, no restated single-source facts.`,
);
