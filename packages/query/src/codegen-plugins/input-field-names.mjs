import { isInputObjectType } from "graphql";

/**
 * graphql-codegen plugin: emit runtime field-name arrays for input types.
 *
 * The UI needs to know — at runtime, derived from the schema — which
 * fields the backend accepts for ordering and filtering. A TypeScript
 * type (`EventOrderByInput`) is erased at runtime, so we can't enumerate
 * it from the generated `.d.ts`. This plugin walks the introspected
 * schema and emits a real `as const` array per matching input type:
 *
 *   export const EVENT_ORDER_BY_FIELDS = ["created", "endDate", ...] as const;
 *
 * It runs as a second `generates` target in src/codegen.ts and produces
 * src/schema-input-fields.generated.ts. Like gql-generated.ts, that file
 * is committed and regenerated by `pnpm --filter @oc-mui/query codegen`
 * against a live backend.
 *
 * Naming: <TypeName> minus the trailing "Input", CONSTANT_CASED, plus
 * "_FIELDS" — e.g. `EventOrderByInput` -> `EVENT_ORDER_BY_FIELDS`.
 *
 * @param {import("graphql").GraphQLSchema} schema
 * @returns {string}
 */
export const plugin = (schema) => {
  const SUFFIXES = ["OrderByInput", "FilterByInput"];

  const lines = [
    "/* eslint-disable */",
    "// AUTO-GENERATED from the GraphQL schema by",
    "// codegen-plugins/input-field-names.mjs — DO NOT EDIT BY HAND.",
    "// Regenerate: pnpm --filter @oc-mui/query codegen",
    "",
  ];

  const typeMap = schema.getTypeMap();
  for (const typeName of Object.keys(typeMap).sort()) {
    if (!SUFFIXES.some((suffix) => typeName.endsWith(suffix))) continue;
    const type = typeMap[typeName];
    if (!isInputObjectType(type)) continue;

    // Sort field names so the output is stable regardless of schema
    // declaration order — keeps the committed file diff-free between
    // regenerations that don't actually change the field set.
    const fields = Object.keys(type.getFields()).sort();
    lines.push(`export const ${toConstName(typeName)} = ${JSON.stringify(fields)} as const;`);
  }

  return lines.join("\n") + "\n";
};

/**
 * `EventOrderByInput` -> `EVENT_ORDER_BY_FIELDS`
 *
 * @param {string} typeName
 * @returns {string}
 */
function toConstName(typeName) {
  return (
    typeName
      .replace(/Input$/, "")
      .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
      .toUpperCase() + "_FIELDS"
  );
}
